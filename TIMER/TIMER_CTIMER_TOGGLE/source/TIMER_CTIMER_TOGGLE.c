#include <stdio.h>
#include "board.h"
#include "peripherals.h"
#include "pin_mux.h"
#include "clock_config.h"
#include "fsl_debug_console.h"


int main(void) {

    /* Init board hardware. */
    BOARD_InitBootPins();
    BOARD_InitBootClocks();
    BOARD_InitBootPeripherals();
#ifndef BOARD_INIT_DEBUG_CONSOLE_PERIPHERAL
    /* Init FSL debug console. */
    BOARD_InitDebugConsole();
#endif

    /* PASO 1: ACTIVACION DEL RELOJ PARA EL PERIFERICO */
	SYSCON -> CLKUNLOCK &= ~SYSCON_CLKUNLOCK_UNLOCK_MASK; // DESBLOQUEO DE PERIFERICO MRCC

	MRCC0 -> MRCC_GLB_CC0 |= MRCC_MRCC_GLB_CC0_CTIMER3_MASK; // HABILITA RELOJ CTIMER3

	MRCC0 -> MRCC_GLB_CC1 |= MRCC_MRCC_GLB_CC1_GPIO1_MASK | // HABILITA RELOJ GRUPO 1
							 MRCC_MRCC_GLB_CC1_PORT1_MASK;

	MRCC0 -> MRCC_GLB_RST0 |= MRCC_MRCC_GLB_RST0_CTIMER3_MASK; // SALE DE MODO RESET

	MRCC0 -> MRCC_GLB_RST1 |= MRCC_MRCC_GLB_RST1_GPIO1_MASK |
							  MRCC_MRCC_GLB_RST1_PORT1_MASK; // SALE DE MODO RESET

	MRCC0 -> MRCC_CTIMER3_CLKSEL = 0x1; // FUENTE DE RELOJ POR FRO (96 MHz) PARA EL TIMER 3
	MRCC0 -> MRCC_CTIMER3_CLKDIV &= ~MRCC_MRCC_CTIMER3_CLKDIV_HALT_MASK; // BORRA BIT HALT ( EVITA BLOQUEO EN MICROCCONTROLADOR)

	SYSCON -> CLKUNLOCK |= SYSCON_CLKUNLOCK_UNLOCK_MASK; // BLOQUEO DE PERIFERICO MRCC

    /* PASO 2: CONFIGURACION DE PIN COMO SALIDA */
	PORT1 -> PCR[14]  |=  0x5 << PORT_PCR_MUX_SHIFT; // PIN GPIO1_14 COMO SALIDA PWM ALTERN FUNCTION ALT5

	/* PASO 3: CONFIGURACION DEL TIMER */
	CTIMER3 -> MCR |= CTIMER_MCR_MR3R_MASK; // RESET TIMER EN CANAL 3 (PERIODO)
	CTIMER3 -> EMR |= 3<<CTIMER_EMR_EMC0_SHIFT; // EXTERNAL MATCH COMO TOOGLE EN CANAL 0 (OUTPUT)
	CTIMER3 -> PR = (SystemCoreClock / 1000) -1; // PR = (96 MHz / 1 KHz)-1 = 95 k TICKS PARA UNA BASE DE TIEMPO DE 1ms
	CTIMER3 -> MR[3] = 500 ; // 500 * 1msbase = 500 ms PARA TIEMPO DE INTERRUPCION DEL PERIODO

	CTIMER3 -> TCR |= CTIMER_TCR_CEN_MASK; // HABILITA EL CONTADOR

	while(1) {
	}
}
