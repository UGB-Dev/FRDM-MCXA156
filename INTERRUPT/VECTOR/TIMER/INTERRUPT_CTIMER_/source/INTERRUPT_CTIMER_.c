#include <stdio.h>
#include "board.h"
#include "peripherals.h"
#include "pin_mux.h"
#include "clock_config.h"
#include "fsl_debug_console.h"


int main(void) {

    /* Init board hardware. */
    BOARD_InitBootPins();
    BOARD_InitBootClocks();
    BOARD_InitBootPeripherals();
#ifndef BOARD_INIT_DEBUG_CONSOLE_PERIPHERAL
    /* Init FSL debug console. */
    BOARD_InitDebugConsole();
#endif

    /* PASO 1: ACTIVACION DEL RELOJ PARA EL PERIFERICO */
	SYSCON -> CLKUNLOCK &= ~SYSCON_CLKUNLOCK_UNLOCK_MASK; // DESBLOQUEO DE PERIFERICO MRCC

	MRCC0 -> MRCC_GLB_CC0 |= MRCC_MRCC_GLB_CC0_CTIMER1_MASK; // HABILITA RELOJ CTIMER1

	MRCC0 -> MRCC_GLB_CC1 |= MRCC_MRCC_GLB_CC1_GPIO3_MASK; // HABILITA RELOJ GRUPO 3

	MRCC0 -> MRCC_GLB_RST0 |= MRCC_MRCC_GLB_RST0_CTIMER1_MASK; // SALE DE MODO RESET

	MRCC0 -> MRCC_GLB_RST1 |= MRCC_MRCC_GLB_RST1_GPIO3_MASK; // SALE DE MODO RESET

	MRCC0 -> MRCC_CTIMER1_CLKSEL = 0x1; // FUENTE DE RELOJ POR FRO (96 MHz) PARA EL TIMER 1
	MRCC0 -> MRCC_CTIMER1_CLKDIV &= ~MRCC_MRCC_CTIMER1_CLKDIV_HALT_MASK; // BORRA BIT HALT ( EVITA BLOQUEO EN MICROCCONTROLADOR)

	SYSCON -> CLKUNLOCK |= SYSCON_CLKUNLOCK_UNLOCK_MASK; // BLOQUEO DE PERIFERICO MRCC

	/* PASO 2: CONFIGURACION DE PIN COMO SALIDA */
	GPIO3 -> PDDR  |=  GPIO_PDDR_PDD12_MASK; // PIN GPIO3_12 (LED ROJO) COMO SALIDA

	/* PASO 3: CONFIGURACION DEL TIMER */
	CTIMER1 -> MCR |= CTIMER_MCR_MR3I_MASK | CTIMER_MCR_MR3R_MASK; // RESET TIMER E INTERRUPCION POR MATCH CANAL 3 (PERIODO)
	CTIMER1 -> PR = (SystemCoreClock / 1000) -1; // PR = (96 MHz / 1 KHz)-1 = 95 k TICKS PARA UNA BASE DE TIEMPO DE 1ms
	CTIMER1 -> MR[3] = 500 ; // 500 * 1msbase = 500 ms PARA TIEMPO DE INTERRUPCION

	CTIMER1 -> TCR |= CTIMER_TCR_CEN_MASK; // HABILITA EL CONTADOR

	/* PASO 3: HABILITACION DE VECTOR DE INTERRUPCION */
	NVIC -> ISER[CTIMER1_IRQn/32] |= 1<<(CTIMER1_IRQn % 32); // HABILITA INTERRUPCION GLOBAL CTIMER1

	while(1) {

	}
}

void CTIMER1_DriverIRQHandler(void){
	if(CTIMER1 -> IR & CTIMER_IR_MR3INT_MASK){
		GPIO3 -> PDOR ^= GPIO_PDOR_PDO12_MASK;
		CTIMER1 -> IR |= CTIMER_IR_MR3INT_MASK; // BORRA BANDERA DE INTERRUPCION
	}
}
